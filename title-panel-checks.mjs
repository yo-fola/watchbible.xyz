// Browser-only checks. All titles and responses below are explicitly synthetic fixtures.
export async function checkTitlePanel() {
  const checks = [];
  const check = (name, condition) => checks.push({ name, passed: Boolean(condition) });
  let createTitlePanel;
  try { ({ createTitlePanel } = await import('./title-panel.mjs')); }
  catch { check('Reusable title-panel module exists', false); return { passed: false, checks }; }
  const host = document.createElement('div');
  host.style.cssText = 'width:min(100%,760px);margin:12px auto';
  document.body.append(host);
  let resolve;
  const pending = new Promise(r => { resolve = r; });
  const requests = [];
  const panel = createTitlePanel(host, { fetchImpl: (...args) => { requests.push(args); return pending; } });
  const candidate = { catalogueId: 'tmdb:movie:901', tmdbId: 901, title: 'Synthetic selection', format: 'movie', year: 2026, posterUrl: null };
  const showing = panel.show(candidate);
  check('Identity renders synchronously while metadata loads', host.textContent.includes('Synthetic selection') && host.textContent.includes('2026') && host.textContent.includes('Movie'));
  check('IMDb is explicitly not connected', host.textContent.includes('IMDb — (not connected)'));
  check('GET uses selected format, id and default region', requests[0]?.[0] === '/api/title?format=movie&id=901&region=NG' && requests[0]?.[1]?.method === 'GET');
  resolve({ ok: true, json: async () => ({ ...candidate, provider: 'TMDB', genres: [], overview: '', anime: null, runtimeMinutes: 112, watch: { region: 'NG', status: 'unlisted', offers: [], link: null, attribution: 'JustWatch' } }) });
  await showing;
  check('Movie duration renders without series counts', host.textContent.includes('112 min') && !host.textContent.includes('seasons') && !host.textContent.includes('episodes'));
  check('Movies do not get a series episode-tracking link', !host.querySelector('.title-panel__episodes-link'));
  check('Resolved metadata is available to parent', panel.getMetadata()?.catalogueId === candidate.catalogueId);
  panel.cancel();

  const hostile = '<img src=x onerror="window.__panelInjected=true">';
  const tv = { ...candidate, catalogueId: 'tmdb:series:902', tmdbId: 902, format: 'series', title: 'Synthetic series', seasons: 0, episodes: 0, runtimeMinutes: 999, anime: true, genres: [{ id: 1, name: hostile }], overview: hostile, imdbRating: 9.9, voteAverage: 8.8, watch: { region: 'NG', status: 'ok', link: 'https://www.themoviedb.org/tv/902-synthetic/watch?locale=NG', attribution: 'JustWatch', offers: ['stream', 'free', 'ads', 'rent', 'buy'].map((kind, i) => ({ providerId: i, name: `Synthetic ${kind}`, kind, logoUrl: null })) } };
  let result = tv;
  let attempts = 0;
  const callbacks = [];
  const rich = createTitlePanel(host, { fetchImpl: async () => { attempts++; if (result instanceof Error) throw result; return { ok: true, json: async () => result }; }, onMetadata: value => callbacks.push(value) });
  await rich.show(tv);
  check('Series shows literal bullet and known-zero counts', host.textContent.includes('0 seasons • 0 episodes') && !host.textContent.includes('999 min'));
  check('Series exposes the correct same-origin episode browser', host.querySelector('.title-panel__episodes-link')?.getAttribute('href') === 'series.html?id=902');
  check('Explicit backend anime tag is a small independent badge', host.querySelector('.title-panel__anime')?.textContent === 'Anime' && host.textContent.includes('Series'));
  check('Genre names and overview remain literal hostile text', host.querySelector('.title-panel__genres')?.textContent === hostile && host.querySelector('.title-panel__overview')?.textContent === hostile && !host.querySelector('[onerror]') && !window.__panelInjected);
  check('Neither TMDB nor fabricated IMDb scores are shown', !host.textContent.includes('9.9') && !host.textContent.includes('8.8') && host.textContent.includes('IMDb — (not connected)'));
  check('Provider offers are grouped by all five kinds', ['stream', 'free', 'ads', 'rent', 'buy'].every(kind => host.querySelector(`[data-watch-kind="${kind}"]`)?.textContent.includes(`Synthetic ${kind}`)));
  const options = [...host.querySelectorAll('a')].filter(a => a.textContent === 'Watch options ↗');
  check('Exactly one verified external watch-options link', options.length === 1 && options[0].href === tv.watch.link && options[0].target === '_blank' && options[0].rel.includes('noopener') && options[0].rel.includes('noreferrer'));
  const attribution = [...host.querySelectorAll('a')].find(a => a.textContent === 'Availability by JustWatch');
  check('Availability region and official JustWatch attribution', host.textContent.includes('NG') && attribution?.href === 'https://www.justwatch.com/');
  await rich.show(tv, { animeOverride: false });
  check('Manual false anime override wins', !host.querySelector('.title-panel__anime'));
  result = { ...tv, anime: null, seasons: null, episodes: null };
  await rich.show(tv, { animeOverride: true });
  check('Manual true override wins over missing backend tag', host.querySelector('.title-panel__anime')?.textContent === 'Anime');
  check('Unknown counts are not zero', host.textContent.includes('Seasons — • Episodes —') && !host.textContent.includes('0 seasons'));
  await rich.show(tv);
  check('Unknown anime has no invented badge', !host.querySelector('.title-panel__anime'));
  result = { ...tv, watch: { ...tv.watch, status: 'unlisted', link: null, offers: [] } };
  await rich.show(tv);
  check('Unlisted is not described as unavailable', host.textContent.includes('Availability not listed') && !host.textContent.toLowerCase().includes('not available'));
  result = { ...tv, watch: { ...tv.watch, status: 'error', offers: [] } };
  await rich.show(tv);
  check('Availability failure retains primary metadata with Retry', rich.getMetadata()?.title === tv.title && host.textContent.includes(hostile) && host.textContent.includes('Availability could not be loaded') && [...host.querySelectorAll('button')].some(b => b.textContent === 'Retry'));
  const beforeRetry = attempts;
  result = tv;
  host.querySelector('button')?.click();
  await new Promise(r => setTimeout(r, 0));
  check('Availability Retry requests details again', attempts === beforeRetry + 1 && host.textContent.includes('Synthetic stream'));
  result = new Error('Synthetic offline');
  await rich.show(tv);
  check('Primary failure retains selected identity and offers Retry', rich.getMetadata() === null && host.textContent.includes(tv.title) && host.textContent.includes('Details could not be loaded') && host.querySelector('button')?.textContent === 'Retry');
  result = { ...tv, catalogueId: 'tmdb:series:WRONG', overview: 'Wrong result must not display' };
  const beforeMismatch = callbacks.length;
  await rich.show(tv);
  check('Mismatching catalogueId is rejected without callback', rich.getMetadata() === null && callbacks.length === beforeMismatch && !host.textContent.includes('Wrong result must not display'));
  result = { ...tv, posterUrl: 'https://evil.example/poster.jpg', backdropUrl: 'javascript:alert(1)', watch: { ...tv.watch, link: 'https://netflix.com/pretend', offers: [{ kind: 'stream', name: hostile, providerId: 9, logoUrl: 'data:image/svg+xml,evil' }] } };
  await rich.show(tv);
  check('Untrusted image URLs never render', ![...host.querySelectorAll('img')].some(image => /evil|data:|javascript:/.test(image.src)));
  check('Unverified service links never become watch-options links', ![...host.querySelectorAll('a')].some(a => a.textContent === 'Watch options ↗'));
  check('Hostile provider names remain text', host.querySelector('[data-watch-kind="stream"]')?.textContent.includes(hostile) && !host.querySelector('[onerror]'));
  result = { ...candidate, runtimeMinutes: 0, anime: null, genres: [], overview: '', watch: null };
  await rich.show(candidate);
  check('Known-zero movie runtime is retained', host.textContent.includes('0 min'));
  result = { ...result, runtimeMinutes: null };
  await rich.show(candidate);
  check('Unknown runtime has an honest placeholder', host.textContent.includes('Runtime —') && !host.textContent.includes('0 min'));

  const safeCover = new URL('./examples/test-cover.svg', import.meta.url).href;
  result = { ...tv, seasons: 1, episodes: 1, posterUrl: safeCover, backdropUrl: safeCover, watch: { ...tv.watch, offers: [{ kind: 'stream', providerId: 1, name: 'Synthetic local fixture', logoUrl: safeCover }] } };
  await rich.show(tv);
  const poster = host.querySelector('.poster-frame img');
  if (poster && !poster.complete) await new Promise(resolve => { poster.addEventListener('load', resolve, { once: true }); poster.addEventListener('error', resolve, { once: true }); });
  check('Safe same-origin synthetic poster loads', poster?.complete && poster?.naturalWidth > 0);
  check('Returned artwork is used behind glass and for provider logos', host.querySelector('.title-panel__backdrop')?.src === safeCover && host.querySelector('.title-panel__provider-logo')?.src === safeCover);
  check('Singular TV facts still use literal bullet', host.textContent.includes('1 season • 1 episode'));
  const desktopCover = host.querySelector('.title-panel__cover').getBoundingClientRect();
  check('Desktop poster is 140px', innerWidth <= 520 || Math.abs(desktopCover.width - 140) < 1);
  result = { ...result, posterUrl: 'http://[invalid', backdropUrl: null };
  await rich.show(tv);
  check('Malformed poster URL has an honest fallback', host.querySelector('.poster-fallback')?.textContent.includes('Cover unavailable'));
  result = { ...tv, watch: { ...tv.watch, link: 'https://www.themoviedb.org/tv/WRONG/watch?locale=NG' } };
  await rich.show(tv);
  check('Official-host URL for another identity is rejected', !host.querySelector('.title-panel__watch-link'));
  result = { ...tv, watch: { ...tv.watch, region: 'GB', link: 'https://www.themoviedb.org/tv/902/watch?locale=GB' } };
  await rich.show(tv, { region: 'GB' });
  check('Explicit region and unslugged TMDB watch link work', host.textContent.includes('Where to watch • GB') && host.querySelector('.title-panel__watch-link')?.href === result.watch.link);
  result = new Error('Synthetic retry failure');
  await rich.show(tv);
  const beforePrimaryRetry = attempts;
  result = tv;
  host.querySelector('button')?.click();
  await new Promise(resolve => setTimeout(resolve, 0));
  check('Primary Retry restores matched details', attempts === beforePrimaryRetry + 1 && rich.getMetadata()?.catalogueId === tv.catalogueId && host.textContent.includes('0 seasons • 0 episodes'));

  const deferred = [];
  const asyncCallbacks = [];
  const racing = createTitlePanel(host, { fetchImpl: (_url, options) => new Promise(resolve => deferred.push({ resolve, signal: options.signal })), onMetadata: value => asyncCallbacks.push(value) });
  const first = racing.show(candidate);
  const second = racing.show(tv);
  deferred[1].resolve({ ok: true, json: async () => tv });
  await second;
  deferred[0].resolve({ ok: true, json: async () => candidate });
  await first;
  check('Independent abort and revision prevent stale selection replacement', deferred[0].signal.aborted && deferred[0].signal !== deferred[1].signal && racing.getMetadata()?.catalogueId === tv.catalogueId && asyncCallbacks.length === 1 && host.textContent.includes(tv.title));
  const third = racing.show(candidate);
  racing.cancel();
  deferred[2].resolve({ ok: true, json: async () => candidate });
  await third;
  check('Cancel invalidates pending rendering and callbacks', deferred[2].signal.aborted && racing.getMetadata() === null && asyncCallbacks.length === 1);

  // A separate real 390px browsing context exercises actual CSS media queries.
  const frame = document.createElement('iframe');
  frame.title = 'Synthetic 390px title-panel layout test';
  frame.style.cssText = 'width:390px;height:720px;border:0;max-width:none;position:absolute;left:0;top:0';
  document.body.append(frame);
  const doc = frame.contentDocument;
  await Promise.all(['theme.css', 'title-panel.css'].map(file => new Promise(resolve => { const link = doc.createElement('link'); link.rel = 'stylesheet'; link.href = new URL(file, import.meta.url).href; link.onload = resolve; link.onerror = resolve; doc.head.append(link); })));
  const mobileHost = doc.createElement('div');
  mobileHost.style.cssText = 'margin:16px;width:calc(100% - 32px)';
  doc.body.append(mobileHost);
  const mobile = createTitlePanel(mobileHost, { fetchImpl: async () => ({ ok: true, json: async () => tv }) });
  await mobile.show(tv);
  const bounds = mobileHost.querySelector('.title-panel').getBoundingClientRect();
  const cover = mobileHost.querySelector('.title-panel__cover').getBoundingClientRect();
  const info = mobileHost.querySelector('.title-panel__info').getBoundingClientRect();
  check('390px layout has no horizontal overflow', doc.documentElement.scrollWidth <= 390 && bounds.right <= 390 && mobileHost.scrollWidth <= mobileHost.clientWidth);
  check('Mobile poster stays 90px left of details', Math.abs(cover.width - 90) < 1 && info.left >= cover.right && info.top < cover.bottom);
  mobile.cancel(); frame.remove();
  rich.cancel(); racing.cancel();
  host.remove();
  return { passed: checks.every(item => item.passed), checks };
}
